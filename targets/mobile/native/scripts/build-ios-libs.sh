#!/bin/sh
# Builds the C++ side (anira, the app's example and its model from models, tanh-lib's AudioIO, the
# engine and host, the AUv3) for the active Xcode platform / configuration and stages it under
# build/ios-<platform>/<config>/staging for Xcode: one static library, libanira_mobile.a (every
# archive of the build and the engines' slices), the headers, and anira_mobile_defines.h (the
# compile definitions the native code was built with, force-included by the pod).
#
# Runs as a pre-compile script phase of both consumers — the NativeAniraJSI
# pod (app) and the AniraAUv3 app extension. Xcode may start the two in
# parallel, so the build is serialised with a lock; the second run is a no-op.
set -e

# Xcode's default PATH is minimal — CMake usually lives in Homebrew.
export PATH="/opt/homebrew/bin:/usr/local/bin:$PATH"

SCRIPT="$(cd "$(dirname "$0")" && pwd)/$(basename "$0")"
cd "$(dirname "${SCRIPT}")/../.."

BUILD_DIR="build/ios-${PLATFORM_NAME}/${CONFIGURATION}"
mkdir -p "${BUILD_DIR}"

if [ -z "${ANIRA_BUILD_LOCKED}" ]; then
  export ANIRA_BUILD_LOCKED=1
  exec /usr/bin/lockf -k "${BUILD_DIR}/.build.lock" "${SCRIPT}"
fi

if [ "${CONFIGURATION}" = "Debug" ]; then
  BUILD_CONFIG="Debug"
else
  BUILD_CONFIG="Release"
fi

if [ "${PLATFORM_NAME}" = "iphoneos" ]; then
  SDK_PATH="$(xcrun --sdk iphoneos --show-sdk-path)"
  SLICE="ios-arm64"
else
  SDK_PATH="$(xcrun --sdk iphonesimulator --show-sdk-path)"
  SLICE="ios-arm64-simulator"
fi

echo "Building the native libraries for ${PLATFORM_NAME} in ${BUILD_CONFIG} configuration"

# The engine options are passed explicitly (not left to the project defaults) so
# a stale CMake cache can never pin an old selection. ANIRA_MOBILE_CMAKE_ARGS
# adds the caller's (e.g. -DFETCHCONTENT_SOURCE_DIR_ANIRA=... for a local anira).
# shellcheck disable=SC2086
cmake -B "${BUILD_DIR}" -S . \
  -DCMAKE_SYSTEM_NAME=iOS \
  -DCMAKE_OSX_SYSROOT="${SDK_PATH}" \
  -DCMAKE_OSX_ARCHITECTURES=arm64 \
  -DCMAKE_OSX_DEPLOYMENT_TARGET=16.4 \
  -DCMAKE_BUILD_TYPE=${BUILD_CONFIG} \
  -DANIRA_WITH_ONNXRUNTIME=ON \
  -DANIRA_WITH_LITERT=ON \
  ${ANIRA_MOBILE_CMAKE_ARGS}

cmake --build "${BUILD_DIR}" --config ${BUILD_CONFIG} --target processor_host anira_auv3 --parallel

# shellcheck disable=SC1091
. "${BUILD_DIR}/staging.env"
STAGE="${BUILD_DIR}/staging"
rm -rf "${STAGE}"
mkdir -p "${STAGE}/lib" "${STAGE}/include"

# One library: every archive of the build and the engines' slices.
ARCHIVES=$(find "${BUILD_DIR}" -name '*.a' -not -path '*/CMakeFiles/*' -not -path "${STAGE}/*")
ORT="$(ls "${ANIRA_SOURCE_DIR}"/modules/onnxruntime-*-iOS-xcframework/onnxruntime.xcframework/${SLICE}/libonnxruntime.a | head -1)"
LITERT="$(ls "${ANIRA_SOURCE_DIR}"/modules/LiteRt-*-iOS-xcframework/LiteRt.xcframework/${SLICE}/libLiteRt.a | head -1)"
# shellcheck disable=SC2086
libtool -static -no_warning_for_no_symbols -o "${STAGE}/lib/libanira_mobile.a" ${ARCHIVES} "${ORT}" "${LITERT}" 2>/dev/null

# The headers the native code includes, merged.
OLD_IFS="${IFS}"
IFS='|'
for DIR in ${INCLUDE_DIRS}; do
  if [ -d "${DIR}" ]; then
    rsync -a --prune-empty-dirs --include='*/' --include='*.h' --include='*.hpp' \
      --include='*.hh' --include='*.inl' --exclude='*' "${DIR}/" "${STAGE}/include/"
  fi
done

# The compile definitions, for the pod to force-include.
{
  echo "// Generated by build-ios-libs.sh: the definitions the native libraries were built with."
  echo "#pragma once"
  for DEFINE in ${DEFINES}; do
    DEFINE="${DEFINE#-D}"
    case "${DEFINE}" in
      *=*) echo "#define ${DEFINE%%=*} ${DEFINE#*=}" ;;
      *) echo "#define ${DEFINE} 1" ;;
    esac
  done
} > "${STAGE}/include/anira_mobile_defines.h"
IFS="${OLD_IFS}"

echo "Staged:"
ls -la "${STAGE}/lib"
